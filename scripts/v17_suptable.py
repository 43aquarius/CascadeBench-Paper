#!/usr/bin/env python3
"""生成补充材料 GLM 九条件表 (tab_s14_glm9.tex): 分方向 BLEU, 2 后端 x 2 参考 x 9 条件 + 斜率摘要。"""
import json, os

A = json.load(open(os.path.join(_ROOT, 'results', 'analysis_v17_glm9.json')))
M9 = A["backend_matrix_9"]
CONDS = ["clean_r", "revr", "rb10", "rb5", "rb25", "rb0", "rbm25", "rbm5", "rn0"]
NAME = {"clean_r": "Clean", "revr": "Reverb (real)", "rb10": "$+10$", "rb5": "$+5$",
        "rb25": "$+2.5$", "rb0": "0", "rbm25": "$-2.5$", "rbm5": "$-5$", "rn0": "TN"}

out = []
out.append("% auto-generated by v17_suptable.py — do not edit by hand")
out.append("Backend / reference & Condition & zh$\\to$en & en$\\to$zh \\\\")
for title, col in [("qwen-mt-uni / oracle", "gummy_vs_oracle"),
                   ("GLM / GLM ref", "glm_vs_glmref"),
                   ("GLM / oracle", "glm_vs_oracle"),
                   ("qwen-mt-uni / GLM ref", "gummy_vs_glmref")]:
    for c in CONDS:
        d = M9[c][col]
        out.append(f"{title} & {NAME[c]} & {d['zh2en']:.1f} & {d['en2zh']:.1f} \\\\")
    out.append("\\addlinespace")

# slopes
out.append("% ---- slopes (OLS over the eight non-clean points) ----")
for k, lbl in [("slope_gummy_9cond_oracleref_noclean", "qwen-mt-uni backend, oracle ref"),
               ("slope_glm_9cond_glmref_noclean", "GLM backend, GLM ref"),
               ("slope_glm_9cond_oracleref_noclean", "GLM backend, oracle ref")]:
    v = A.get(k, {})
    for lang, d in v.items():
        out.append(f"% {lbl} {lang}: slope={d['slope']} intercept={d['intercept']} r={d['r']} "
                   f"x={d['x']} y={d['y']}")

dst = os.path.join(_ROOT, 'paper', 'latex', 'supp_tables', 'tab_s14_glm9.tex')
open(dst, 'w').write('\n'.join(out) + '\n')
print("written", dst, f"({len(out)} lines)")
